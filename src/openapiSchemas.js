const DEVICE_ROLES = ['consumer', 'source', 'storage', 'distribution', 'converter', 'enclosure']
const CONDUCTOR_TYPES = ['positive', 'negative', 'line', 'neutral', 'earth', 'signal']

const str = (description, extra = {}) => ({ type: 'string', description, ...extra })
const num = (description, extra = {}) => {
  const { unit, ...rest } = extra
  return { type: 'number', description, ...(unit ? { 'x-unit': unit } : {}), ...rest }
}
const int = (description, extra = {}) => ({ type: 'integer', description, ...extra })
const bool = (description) => ({ type: 'boolean', description })
const list = (items, description) => ({ type: 'array', items, description })
const ref = (name) => ({ $ref: `#/components/schemas/${name}` })
const nullable = (schema) => ({ ...schema, nullable: true })
const obj = (properties, description, extra = {}) => ({ type: 'object', ...(description ? { description } : {}), properties, ...extra })
